"""Build a story-text <-> CG cross-reference index for NIKKE.

单一事实源：不再直接解析 Dialog mpk，而是读取各剧情导出脚本的 JSON 产物，
行内 `cg` 字段（CG 发生变化的行）就是转场记录——索引与剧情 Markdown 标记
天然同口径。mpk 的行级解析只在 export_mainstory / export_rest / export_story_v2
里做一次。

Source of truth (all local, generated by the export scripts):
  * 主线剧情/主线剧情_全量.json                      -> 50 章（chapter 1 按游戏
    边界拆成 d_main_00 坠落 / d_main_01 侵蚀，与 nikke-web build_db 的切法一致）
  * 其他剧情/<类>/<类>_全量.json                     -> 活动/个人/咨询/支线/外传/…
  * 其他剧情/活动剧情/Marian/event_marian_结构化.json -> 玛丽安活动（不在活动全量里）
  * CG/ 全量分类/**/*.png + *.atlas                  -> exported CG library

Outputs (CG索引/):
  * 剧情CG对照索引.csv
  * 剧情CG对照索引.json
  * CG剧情档案.csv          每张 CG 的剧情出处汇总
  * 统计.txt
"""
from __future__ import annotations

import csv
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import cg_refs

BASE = Path(__file__).resolve().parents[1]
OUT = BASE / "CG索引"

CATS = ["活动剧情", "妮姬个人剧情", "咨询对话", "支线剧情",
        "外传与前哨基地日常", "支线故事", "短信与日常对话", "补充剧情文本"]

COLS = ["分类", "活动/章节", "活动键", "小节", "小节标题", "行号", "台词ID",
        "说话人", "台词", "CG名", "动态模型", "背景板", "静态图", "动态CG", "匹配"]


def game_bucket_of(chapter: int, group: str) -> str:
    """主线小节 -> 游戏章节 bucket（与 nikke-web build_db.collect_story_units 同规则）。"""
    if chapter == 1:
        m = re.match(r"^d_main_01_(\d+)", group)
        return "d_main_00" if m and int(m.group(1)) <= 3 else "d_main_01"
    return f"d_main_{chapter:02d}"


def iter_main():
    """主线 50 章。"""
    path = BASE / "主线剧情" / "主线剧情_全量.json"
    d = json.loads(path.read_text(encoding="utf-8"))
    for ch in d.get("chapters", []):
        bucket_map = {}
        for sec in ch.get("sections", []):
            g = sec.get("group") or ""
            bucket = game_bucket_of(ch["chapter"], g)
            bucket_map.setdefault(bucket, ch.get("title") or "")
            for l in sec.get("lines") or []:
                yield {
                    "分类": "主线剧情",
                    "活动/章节": f"第{ch['chapter']:02d}章" + (f" · {ch['title']}" if ch.get("title") else ""),
                    "活动键": bucket,
                    "小节": g,
                    "小节标题": "",
                    "行号": l.get("n"),
                    "台词ID": l.get("key") or "",
                    "说话人": l.get("speaker") or "",
                    "台词": (l.get("zh-CN") or "").strip(),
                    "_cg": l.get("cg") or [],
                    "_cgd": l.get("cgd") or "",
                    "_cgb": l.get("cgb") or "",
                }


def iter_rest(cat: str):
    """其他剧情各类：<类>_全量.json = [{bucket,title,groups:[{group,title,lines}]}]。"""
    path = BASE / "其他剧情" / cat / f"{cat}_全量.json"
    if not path.exists():
        return
    d = json.loads(path.read_text(encoding="utf-8"))
    for unit in d:
        bucket = unit.get("bucket") or ""
        unit_title = unit.get("title") or bucket
        for grp in unit.get("groups") or []:
            for l in grp.get("lines") or []:
                yield {
                    "分类": cat,
                    "活动/章节": unit_title,
                    "活动键": bucket,
                    "小节": grp.get("group") or "",
                    "小节标题": grp.get("title") or "",
                    "行号": l.get("n"),
                    "台词ID": l.get("key") or "",
                    "说话人": l.get("speaker") or "",
                    "台词": (l.get("zh-CN") or "").strip(),
                    "_cg": l.get("cg") or [],
                    "_cgd": l.get("cgd") or "",
                    "_cgb": l.get("cgb") or "",
                }


def iter_marian():
    """玛丽安活动：活动全量之外的独立结构化 JSON。"""
    path = BASE / "其他剧情" / "活动剧情" / "Marian" / "event_marian_结构化.json"
    if not path.exists():
        return
    d = json.loads(path.read_text(encoding="utf-8"))
    for ch in d.get("chapters", []):
        for l in ch.get("lines") or []:
            yield {
                "分类": "活动剧情",
                "活动/章节": "玛丽安（Marian）",
                "活动键": "event_marian",
                "小节": ch.get("group") or "",
                "小节标题": ch.get("label") or "",
                "行号": l.get("n"),
                "台词ID": l.get("key") or "",
                "说话人": l.get("speaker") or "",
                "台词": (l.get("zh-CN") or "").strip(),
                "_cg": l.get("cg") or [],
                "_cgd": l.get("cgd") or "",
                "_cgb": l.get("cgb") or "",
            }


def main() -> None:
    stats_only = "--stats" in sys.argv

    static_cg, dynamic_cg = cg_refs.load_cg_library()

    rows = []
    missing_files: Counter = Counter()
    cg_seen: Counter = Counter()
    per_category: Counter = Counter()
    units_per_cg: dict[str, set] = defaultdict(set)
    match_kind = Counter()

    sources = [iter_main(), iter_marian()] + [iter_rest(c) for c in CATS]
    for src in sources:
        for r in src:
            for cg in r.pop("_cg"):
                row = {k: r[k] for k in COLS if k in r}
                row["CG名"] = cg
                row["动态模型"] = r.get("_cgd", "")
                row["背景板"] = r.get("_cgb", "")
                sfile, dmodel, match = cg_refs.resolve_cg(cg, static_cg, dynamic_cg)
                row["静态图"] = sfile or ""
                row["动态CG"] = dmodel or ""
                row["匹配"] = match
                if sfile is None and dmodel is None:
                    missing_files[cg] += 1
                match_kind[match] += 1
                cg_seen[cg] += 1
                units_per_cg[cg].add(row["活动键"])
                per_category[row["分类"]] += 1
                rows.append(row)

    print(f"rows {len(rows)}, distinct CG {len(cg_seen)}")
    print("rows by category", dict(per_category))
    print("match quality", dict(match_kind))
    print(f"CG refs without exported file: {len(missing_files)} distinct / "
          f"{sum(missing_files.values())} refs")
    for k, v in missing_files.most_common(12):
        print("   ", k, v)
    no_index = sorted(n for n in static_cg
                      if n not in {c.lower() for c in cg_seen})
    print(f"exported static CG not referenced by any dialog: {len(no_index)}")

    if stats_only:
        return

    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / "剧情CG对照索引.csv").open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLS)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    (OUT / "剧情CG对照索引.json").write_text(
        json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")

    # 每张 CG 的剧情出处档案
    with (OUT / "CG剧情档案.csv").open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["CG名", "引用次数", "出现剧情单元数", "静态图", "动态CG", "匹配",
                    "出现剧情单元", "首次出处(小节/行号)"])
        first: dict[str, tuple] = {}
        for r in rows:
            first.setdefault(r["CG名"], (r["小节"], r["行号"]))
        for cg, n in cg_seen.most_common():
            sfile, dmodel, match = cg_refs.resolve_cg(cg, static_cg, dynamic_cg)
            units = "；".join(sorted(units_per_cg[cg]))
            w.writerow([cg, n, len(units_per_cg[cg]), sfile or "", dmodel or "", match,
                        units, f"{first[cg][0]}/{first[cg][1]}"])

    unref = sorted(n for n in static_cg if n not in {c.lower() for c in cg_seen})
    with (OUT / "统计.txt").open("w", encoding="utf-8") as fh:
        fh.write(f"索引条目 {len(rows)}，涉及 CG {len(cg_seen)}（转场口径：只在 CG 变化的行记录）\n")
        fh.write(f"分类分布 {dict(per_category)}\n")
        fh.write(f"匹配质量 {dict(match_kind)}\n")
        fh.write(f"引用但无导出文件的 CG：{len(missing_files)} 个\n")
        for k, v in missing_files.most_common():
            fh.write(f"  {k}\t{v}\n")
        fh.write(f"\n已导出但剧情中未引用的静态 CG：{len(unref)} 个\n")
        for n in unref:
            fh.write(f"  {n}\n")
    print("written", OUT / "剧情CG对照索引.csv")


if __name__ == "__main__":
    main()
